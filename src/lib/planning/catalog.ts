import type { DestinationId, TravelMode, TripItemKind } from "./types";

/** Curated option used for planning, swaps, and server-side price recomputation. */
export interface CatalogOption {
  catalogId: string;
  kind: TripItemKind;
  title: string;
  location: string;
  costAED: number;
  photo?: string;
  mode?: TravelMode;
  defaultStartTime?: string;
  durationMin?: number;
  notes?: string;
  tags?: string[];
  /**
   * Shared place key (e.g. `jebel-jais`, `hatta-dam`). A trip visits each
   * non-repeatable area at most once, even across different catalog items.
   */
  area?: string;
  /** When true, the same venue/area may appear more than once. Default false. */
  repeatable?: boolean;
}

export interface DestinationHighlightSpec {
  /** Must match a real plan catalogId included in the trip. */
  catalogId: string;
  /** Short label for UI chrome. */
  label: string;
  /** Sentence shown only when that item is on the trip at an accepted time. */
  copy: string;
  /** Inclusive HH:MM window for the highlight timing to count. */
  earliestStart: string;
  latestStart: string;
  cutoffTime?: string;
}

export interface DestinationCatalog {
  id: DestinationId;
  label: string;
  originLabel: string;
  travel: CatalogOption[];
  hotels: CatalogOption[];
  plans: CatalogOption[];
  highlight: DestinationHighlightSpec;
}

